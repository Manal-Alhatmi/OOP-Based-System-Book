public class HistoryBook {
    private String era;
    private String author;
    private boolean containsMaps;

    public HistoryBook() {}

    public String getEra() {
        return era;
    }

    public void setEra(String era) {
        this.era = era;
    }

    public String getAuthor() {
        return author;
    }

    public void setAuthor(String author) {
        this.author = author;
    }

    public boolean isContainsMaps() {
        return containsMaps;
    }

    public void setContainsMaps(boolean containsMaps) {
        this.containsMaps = containsMaps;
    }
}