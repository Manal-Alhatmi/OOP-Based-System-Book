public class DesignBook {
    private String designField;
    private boolean includesTemplates;

    public DesignBook() {}

    public String getDesignField() {
        return designField;
    }

    public void setDesignField(String designField) {
        this.designField = designField;
    }

    public boolean isIncludesTemplates() {
        return includesTemplates;
    }

    public void setIncludesTemplates(boolean includesTemplates) {
        this.includesTemplates = includesTemplates;
    }
}
